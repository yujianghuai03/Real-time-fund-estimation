    `fund_company` VARCHAR(128) DEFAULT NULL COMMENT '基金公司',
    `manager_name` VARCHAR(128) DEFAULT NULL COMMENT '基金经理',
    `risk_level` TINYINT DEFAULT NULL COMMENT '风险等级: 1低 2中低 3中 4中高 5高',
