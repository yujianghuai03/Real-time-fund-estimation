    `tenant_id` BIGINT NOT NULL COMMENT '租户ID，关联sys_tenant.id',
    `fund_code` VARCHAR(32) NOT NULL COMMENT '基金代码',
    `fund_name` VARCHAR(128) NOT NULL COMMENT '基金名称',
